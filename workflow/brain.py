HEADING_RE = re.compile(r'^(#{1,6})\s+(.+)$')
# Unicode-aware on purpose: the repo is English but the clone that borrows this
# scorer is Turkish, and an ASCII class silently shreds "köpek" into "k" and
# "pek", which then matches everything.
TOKEN = re.compile(r"[^\W_]+(?:['’_-][^\W_]+)*", re.UNICODE)
COMBINING_DOT = '\u0307'
CHUNK_MAX_LINES = 120


def fold(text):
    """Lowercase for matching.

    Turkish İ lowercases to i plus a combining dot, so "İnanç" and "inanç" would
    otherwise be different tokens. Drop the mark.
    """
    return text.lower().replace(COMBINING_DOT, '')


def scope_of(path):
    parts = Path(path).resolve().relative_to(REPO_ROOT).parts
    if parts[0] == 'brain':
        return 'brain'
    if parts[0] == 'blog':
        return 'blog'
    if Path(path).suffix == '.md':
        return 'ops'
    return 'code'


def corpus_files(scopes):
    for path in sorted(REPO_ROOT.rglob('*')):
        if not path.is_file():
            continue
        parts = path.relative_to(REPO_ROOT).parts
        if set(parts) & SEARCH_SKIP_DIRS:
            continue
        if path.suffix != '.md' and path.suffix not in CODE_SUFFIXES and path.name != 'Makefile':
            continue
        scope = scope_of(path)
        if scope in scopes:
            yield path, scope


def chunks_of(path, scope):
    """Heading-aware chunks, so a hit points at a section, not a whole file."""
    lines = read(path).split('\n')
    chunks, buf, heading, start = [], [], '', 1

    def flush():
        if any(line.strip() for line in buf):
            chunks.append({'path': rel(path), 'scope': scope, 'heading': heading,
                           'line': start, 'lines': list(buf), 'text': '\n'.join(buf)})

    for i, line in enumerate(lines, start=1):
        match = HEADING_RE.match(line) if path.suffix == '.md' else None
        if match or len(buf) >= CHUNK_MAX_LINES:
            flush()
            buf, start = [], i
            if match:
                heading = match.group(2).strip()
        buf.append(line)
    flush()
    return chunks


def index_chunks(chunks):
    """Add the token counts the scorer needs. Any caller can build the chunks."""
    for chunk in chunks:
        chunk['tokens'] = Counter(TOKEN.findall(fold(chunk['text'])))
        chunk['label_tokens'] = set(TOKEN.findall(fold(chunk['heading'] + ' ' + chunk['path'])))
    return chunks


def build_corpus(scopes):
    chunks = []
    for path, scope in corpus_files(scopes):
        chunks.extend(chunks_of(path, scope))
    return index_chunks(chunks)


def search(query, scopes, limit=8, chunks=None):
    """Rank chunks against a query.

    `chunks` lets another corpus borrow this scorer instead of copying it:
    mind.py indexes a store outside the repo and passes it in. Default is the
    repo corpus.
    """
    chunks = build_corpus(scopes) if chunks is None else chunks
    if not chunks:
        return []
    terms = [t for t in TOKEN.findall(fold(query))]
    if not terms:
        return []
    doc_freq = Counter()
    for chunk in chunks:
        for term in set(terms):
            if chunk['tokens'].get(term):
                doc_freq[term] += 1
    total = len(chunks)
    phrase = fold(query).strip()

    scored = []
    for chunk in chunks:
        score = 0.0
        hits = 0
        for term in terms:
            tf = chunk['tokens'].get(term, 0)
            if not tf:
                continue
            hits += 1
            idf = math.log((total + 1) / (doc_freq[term] + 1)) + 1.0
            score += (1 + math.log(tf)) * idf
            if term in chunk['label_tokens']:
                score += 1.5 * idf
        if not hits:
            continue
        score *= (hits / len(terms)) ** 1.5          # reward chunks covering the whole query
        if len(phrase) > 6 and phrase in fold(chunk['text']):
            score += 6.0
        scored.append((score, chunk))

    scored.sort(key=lambda pair: (-pair[0], pair[1]['path'], pair[1]['line']))
    results = []
    for score, chunk in scored[:limit]:
        best_line, best_hits, offset = '', 0, 0
        for i, line in enumerate(chunk['lines']):
            found = sum(1 for term in set(terms) if term in fold(line))
            if found > best_hits:
                best_line, best_hits, offset = line.strip(), found, i
        results.append({'score': round(score, 2), 'path': chunk['path'],
                        'line': chunk['line'] + offset, 'heading': chunk['heading'],
                        'snippet': ' '.join(best_line.split())[:220] or ' '.join(chunk['text'].split())[:220]})
    return results


