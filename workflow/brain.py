def context():
    """Everything the renderers need, parsed once."""
    log = parse_incident_log()
    articles = parse_articles()
    return {
        'rules': log['rules'],
        'incidents': log['incidents'],
        'open_issues': log['open_issues'],
        'articles': articles,
        'topics': parse_topic_pool(articles),
        'sources': parse_sources(),
        'enforcement': parse_enforcement(),
    }


def curated_docs():
    """Hand-written brain files, in reading order, with their one-line purpose."""
    generated = set(GENERATED.keys())
    docs = []
    for path in sorted(BRAIN.rglob('*.md')) if BRAIN.is_dir() else []:
        if rel(path) in generated:
            continue
        text = read(path)
        docs.append({'path': rel(path), 'title': first_heading(text, path.stem),
                     'purpose': first_prose(text)})
    order = {'brain/README.md': 0, 'brain/decisions.md': 1}
    docs.sort(key=lambda d: (order.get(d['path'], 2), d['path']))
    return docs


