BLOG = REPO_ROOT / 'blog'
INCIDENT_LOG = WORKFLOW / 'incident-log.md'
ROADMAP = REPO_ROOT / 'ROADMAP.md'


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_cr = _load('check_rules', WORKFLOW / 'check-rules.py')
_mpk = _load('make_paste_kit', WORKFLOW / 'make_paste_kit.py')

# The linter's own BLOCKING list. Generated files mirror upstream prose, and
# upstream prose sometimes quotes a banned pattern under a pragma. Re-deriving
# the ban list here would let the two drift, so we import it.
BLOCKING_PATTERNS = [pattern for _, pattern, _ in _cr.BLOCKING]
ALLOW_PRAGMA = '<!-- check-rules: allow -->'

GENERATED_BANNER = (
    '<!-- GENERATED by `python3 workflow/brain.py build`. Do not hand-edit: '
    'edits are overwritten on the next build and CI fails on drift. -->'
)

# Enforcement markers. Any file may claim it enforces a rule by carrying
# `brain-rule: <rule-id>` in a comment. The registry reads those claims back so
# the brain knows which of its rules a machine checks and which ride on
# discipline alone.
MARKER = re.compile(r'brain-rule:\s*(R-[a-z0-9-]+)')
RULE_REF = re.compile(r'\bR-[a-z0-9-]{4,}\b')
DECISION_REF = re.compile(r'\bD-\d{3}\b')

SEARCH_SKIP_DIRS = {'.git', '.venv', 'node_modules', '__pycache__'}
CODE_SUFFIXES = {'.py', '.sh', '.yml', '.yaml', '.json', '.css', '.tsx'}


