def cmd_build(args):
    BRAIN.mkdir(parents=True, exist_ok=True)
    ctx = context()
    changed = []
    for relpath, renderer in sorted(GENERATED.items()):
        path = REPO_ROOT / relpath
        expected = renderer(ctx)
        if path.exists() and read(path) == expected:
            print('  unchanged  %s' % relpath)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected, encoding='utf-8')
        changed.append(relpath)
        print('  wrote      %s' % relpath)
    print('\n%d of %d registries rewritten from source.' % (len(changed), len(GENERATED)))
    return 0


def cmd_check(args):
    findings = check()
    fails = [f for f in findings if f[0] == 'FAIL']
    warns = [f for f in findings if f[0] == 'WARN']
    for level, message in findings:
        if level == 'WARN' and args.quiet:
            continue
        print('  [%s] %s' % (level, message), file=sys.stderr)
    print('\n%d FAIL, %d WARN.' % (len(fails), len(warns)), file=sys.stderr)
    if fails:
        print('The brain no longer matches the repo it describes. Rebuild or fix the '
              'reference, then commit the result.', file=sys.stderr)
        return 1
    if warns and args.strict:
        return 1
    return 0


def cmd_search(args):
    scopes = {'brain', 'ops', 'blog', 'code'} if args.scope == 'all' else {args.scope}
    results = search(' '.join(args.query), scopes, args.limit)
    if not results:
        print('No match for %r in scope %s.' % (' '.join(args.query), args.scope), file=sys.stderr)
        return 1
    for i, hit in enumerate(results, start=1):
        where = '%s:%d' % (hit['path'], hit['line'])
        print('%2d. %-56s %s' % (i, where, ('[%s]' % hit['heading']) if hit['heading'] else ''))
        print('    %s' % hit['snippet'])
    return 0


def cmd_rules(args):
    ctx_rules = parse_incident_log()['rules']
    enforcement = parse_enforcement()
    matches = []
    for rule in ctx_rules:
        if args.category and args.category.lower() not in rule['category_id']:
            continue
        if args.id and args.id.lower() not in rule['id']:
            continue
        if args.grep and args.grep.lower() not in (rule['label'] + ' ' + rule['statement']).lower():
            continue
        matches.append(rule)
    if not matches:
        print('No rule matches that filter.', file=sys.stderr)
        return 1
    for rule in matches:
        marks = enforcement.get(rule['id'], [])
        print('%s  (%s)' % (rule['id'], rule['category']))
        print('  %s: %s' % (rule['label'], rule['statement']))
        print('  source: workflow/incident-log.md:%d   enforced by: %s'
              % (rule['line'], ', '.join(marks) if marks else 'procedural'))
        print('')
    print('%d of %d rules.' % (len(matches), len(ctx_rules)))
    return 0


def cmd_stats(args):
    ctx = context()
    chunks = build_corpus({'brain', 'ops', 'blog', 'code'})
    words = sum(sum(c['tokens'].values()) for c in chunks)
    by_category = Counter(r['category'] for r in ctx['rules'])
    by_status = Counter(a['status'] for a in ctx['articles'])
    enforced = len([r for r in ctx['rules'] if ctx['enforcement'].get(r['id'])])
    incidents = ctx['incidents']

    print('Corpus      %d files, %d chunks, %d words indexed'
          % (len({c['path'] for c in chunks}), len(chunks), words))
    print('Rules       %d active, %d with an automated check' % (len(ctx['rules']), enforced))
    for category, count in by_category.most_common():
        print('              %-24s %d' % (category, count))
    print('Incidents   %d logged, newest %s, %d open issues'
          % (len(incidents), max((i['date'] for i in incidents), default='none'), len(ctx['open_issues'])))
    print('Articles    %d folders' % len(ctx['articles']))
    for status, count in by_status.most_common():
        print('              %-24s %d' % (status, count))
    print('Topics      %d in pool, %d matched to an article'
          % (len(ctx['topics']), len([t for t in ctx['topics'] if t['covered_by']])))
    return 0


def main():
    parser = argparse.ArgumentParser(description='The operation brain: index and recall.')
    sub = parser.add_subparsers(dest='command')

    sub.add_parser('build', help='regenerate the brain registries from their sources').set_defaults(func=cmd_build)

    check_parser = sub.add_parser('check', help='fail when the brain no longer matches the repo')
    check_parser.add_argument('--strict', action='store_true', help='treat warnings as failures')
    check_parser.add_argument('--quiet', action='store_true', help='print failures only')
    check_parser.set_defaults(func=cmd_check)

    search_parser = sub.add_parser('search', help='ranked recall across the repo')
    search_parser.add_argument('query', nargs='+')
    search_parser.add_argument('--scope', default='all', choices=['all', 'brain', 'ops', 'blog', 'code'])
    search_parser.add_argument('--limit', type=int, default=8)
    search_parser.set_defaults(func=cmd_search)

    rules_parser = sub.add_parser('rules', help='print the rules in force')
    rules_parser.add_argument('--category', help='filter by category id, e.g. tooling')
    rules_parser.add_argument('--id', help='filter by rule id fragment')
    rules_parser.add_argument('--grep', help='filter by text in the label or statement')
    rules_parser.set_defaults(func=cmd_rules)

    sub.add_parser('stats', help='what the brain currently holds').set_defaults(func=cmd_stats)

    args = parser.parse_args()
    if not getattr(args, 'func', None):
        parser.print_help()
        return 2
    return args.func(args)


