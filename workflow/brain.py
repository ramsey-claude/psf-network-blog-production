def rel(path):
    """Repo-relative path string, for stable output across machines."""
    path = Path(path)
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def slugify(text, max_len=44):
    """Stable id fragment from a human label."""
    text = re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')
    if len(text) <= max_len:
        return text
    cut = text[:max_len]
    if '-' in cut:
        cut = cut.rsplit('-', 1)[0]
    return cut.strip('-')


def sanitize(line):
    """Carry the linter pragma onto a generated line that quotes a ban.

    Generated files sit inside the linted scope, and their content is lifted
    from sources where a banned pattern is quoted on purpose (the ban list
    itself, an incident that names the word it caught). Upstream carries a
    pragma on those lines; a mirror of the line has to carry it too, or the
    brain would fail the very rules it publishes.
    """
    if not line.strip() or ALLOW_PRAGMA in line:
        return line
    for pattern in BLOCKING_PATTERNS:
        if pattern.search(line):
            return line.rstrip() + '  ' + ALLOW_PRAGMA
    return line


def emit(lines):
    """Join generated lines, sanitizing each, with a trailing newline."""
    return '\n'.join(sanitize(ln) for ln in lines).rstrip('\n') + '\n'


def read(path):
    try:
        return Path(path).read_text(encoding='utf-8')
    except (OSError, UnicodeDecodeError):
        return ''


def first_heading(text, default=''):
    for line in text.split('\n'):
        if line.startswith('# '):
            return line[2:].strip()
    return default


def first_prose(text, limit=200):
    """First prose sentence of a document, for one-line index summaries.

    Paragraphs in this repo are hard-wrapped, so the first sentence is usually
    spread over two or three physical lines. Gather the paragraph first, then
    cut at the sentence.
    """
    body = re.sub(r'^---\n.*?\n---\n', '', text, flags=re.S)
    paragraph = []
    for line in body.split('\n'):
        stripped = line.strip()
        if not stripped or stripped.startswith(('#', '>', '|', '-', '*', '`', '<!--', '[![')):
            if paragraph:
                break
            continue
        paragraph.append(stripped)
    if not paragraph:
        return ''
    joined = ' '.join(paragraph)
    joined = re.sub(r'\*\*(.+?)\*\*', r'\1', joined)
    joined = re.sub(r'`(.+?)`', r'\1', joined)
    joined = re.sub(r'\[(.+?)\]\([^)]*\)', r'\1', joined)
    return re.split(r'(?<=[.!?])\s', joined)[0].strip()[:limit]


def cell(text, limit=None):
    """Make a string safe to drop into a markdown table cell."""
    text = ' '.join(str(text).split()).replace('|', '/')
    if limit and len(text) > limit:
        text = text[:limit - 1].rstrip() + '…'
    return text


