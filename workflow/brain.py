MD_LINK = re.compile(r'\[[^\]]*\]\(([^)]+)\)')


def brain_pages():
    pages = [REPO_ROOT / 'CLAUDE.md']
    if BRAIN.is_dir():
        pages += sorted(BRAIN.rglob('*.md'))
    return [p for p in pages if p.exists()]


def check():
    """Every way the brain can be wrong that a machine can see."""
    findings = []
    ctx = context()

    for relpath, renderer in sorted(GENERATED.items()):
        path = REPO_ROOT / relpath
        expected = renderer(ctx)
        if not path.exists():
            findings.append(('FAIL', '%s is missing. Run: python3 workflow/brain.py build' % relpath))
        elif read(path) != expected:
            findings.append(('FAIL', '%s has drifted from its sources. Run: python3 workflow/brain.py build' % relpath))

    seen = {}
    for rule in ctx['rules']:
        if rule['id'] in seen:
            findings.append(('FAIL', 'duplicate rule id %s at incident-log.md:%d and :%d, rename one label'
                             % (rule['id'], seen[rule['id']], rule['line'])))
        seen[rule['id']] = rule['line']
        if not rule['statement']:
            findings.append(('FAIL', 'rule %s has an empty statement at incident-log.md:%d'
                             % (rule['id'], rule['line'])))

    known_rules = set(seen)
    decisions = set(DECISION_REF.findall(read(BRAIN / 'decisions.md')))
    for page in brain_pages():
        text = read(page)
        is_generated = rel(page) in GENERATED
        if is_generated and not text.startswith('<!-- GENERATED'):
            findings.append(('FAIL', '%s lost its generated banner' % rel(page)))
        if not is_generated and text.startswith('<!-- GENERATED'):
            findings.append(('FAIL', '%s carries a generated banner but nothing builds it' % rel(page)))
        for rule_id in set(RULE_REF.findall(text)):
            if rule_id not in known_rules:
                findings.append(('FAIL', '%s cites %s, which is not in the rules registry' % (rel(page), rule_id)))
        for decision_id in set(DECISION_REF.findall(text)):
            if decision_id not in decisions and rel(page) != 'brain/decisions.md':
                findings.append(('FAIL', '%s cites %s, which is not in brain/decisions.md' % (rel(page), decision_id)))
        for target in MD_LINK.findall(text):
            target = target.split('#')[0].split(' ')[0].strip()
            if not target or target.startswith(('http://', 'https://', 'mailto:')):
                continue
            if not (page.parent / target).exists():
                findings.append(('FAIL', '%s links to %s, which does not exist' % (rel(page), target)))

    for rule in ctx['rules']:
        if not ctx['enforcement'].get(rule['id']):
            findings.append(('WARN', 'rule %s has no automated check, it rides on discipline' % rule['id']))

    for article in ctx['articles']:
        if article['status'] == 'empty':
            findings.append(('WARN', 'blog/%s holds no draft' % article['slug']))

    return findings


