FIELD_BULLET = re.compile(r'^-\s+\*\*(.+?):?\*\*:?\s*(.*)$')
DATED_ENTRY = re.compile(r'^#{2,3}\s+(\d{4}-\d{2}-\d{2}):\s*(.+)$')
H2 = re.compile(r'^##\s+(.+)$')
H3 = re.compile(r'^###\s+(.+)$')


def parse_incident_log(text=None):
    """Split the incident log into active rules, incidents, and open issues.

    The log is the pipeline's long-term memory and its format is stable by
    convention, not by schema: `## Active rules` holds `### Category` groups of
    `- **Label:** statement` bullets, dated `### YYYY-MM-DD: headline` blocks
    hold incidents with `- **Field:** value` bodies, and `## Open issues` holds
    known limitations. Continuation lines belong to whatever bullet opened.
    """
    text = read(INCIDENT_LOG) if text is None else text
    rules, incidents, open_issues = [], [], []
    section = ''
    category = category_id = ''
    rule = incident = issue = None
    field = None

    def close_rule():
        nonlocal rule
        if rule:
            rule['statement'] = ' '.join(rule['statement'].split())
            rules.append(rule)
            rule = None

    def close_incident():
        nonlocal incident, field
        if incident:
            incident['fields'] = {k: ' '.join(v.split()) for k, v in incident['fields'].items()}
            incidents.append(incident)
            incident = None
        field = None

    def close_issue():
        nonlocal issue
        if issue:
            issue['text'] = ' '.join(issue['text'].split())
            open_issues.append(issue)
            issue = None

    for lineno, line in enumerate(text.split('\n'), start=1):
        dated = DATED_ENTRY.match(line)
        if dated:
            close_rule()
            close_incident()
            close_issue()
            incident = {'date': dated.group(1), 'headline': dated.group(2).strip(),
                        'section': section or 'Incident history', 'fields': {}, 'line': lineno}
            continue

        h2 = H2.match(line)
        if h2:
            close_rule()
            close_incident()
            close_issue()
            section = h2.group(1).strip()
            category = category_id = ''
            continue

        h3 = H3.match(line)
        if h3:
            close_rule()
            close_issue()
            if section.startswith('Active rules'):
                category = h3.group(1).strip()
                category_id = slugify(category)
            continue

        bullet = FIELD_BULLET.match(line)
        if bullet and section.startswith('Active rules') and category:
            close_rule()
            label = bullet.group(1).strip()
            rule = {'category': category, 'category_id': category_id, 'label': label,
                    'id': 'R-%s-%s' % (category_id, slugify(label)),
                    'statement': bullet.group(2).strip(), 'line': lineno}
            continue
        if bullet and incident is not None:
            field = bullet.group(1).strip().lower()
            incident['fields'][field] = bullet.group(2).strip()
            continue
        if bullet and section.startswith('Open issues'):
            close_issue()
            issue = {'label': bullet.group(1).strip(), 'text': bullet.group(2).strip(), 'line': lineno}
            continue

        # Continuation: an indented or plain line under whatever bullet is open.
        stripped = line.strip()
        if not stripped or stripped == '---':
            continue
        if rule is not None:
            rule['statement'] += ' ' + stripped
        elif issue is not None:
            issue['text'] += ' ' + stripped
        elif incident is not None and field:
            incident['fields'][field] += ' ' + stripped

    close_rule()
    close_incident()
    close_issue()

    seen = {}
    for r in rules:
        if r['id'] in seen:
            r['duplicate_of'] = seen[r['id']]
        else:
            seen[r['id']] = r['line']
    return {'rules': rules, 'incidents': incidents, 'open_issues': open_issues}


def parse_enforcement():
    """Map rule id to the files that claim to enforce it.

    A claim is a `brain-rule: R-...` marker in a comment. Nothing under brain/
    is scanned: the registry lists rule ids by definition and would otherwise
    report itself as its own enforcement.
    """
    found = defaultdict(list)
    for path in sorted(REPO_ROOT.rglob('*')):
        if not path.is_file():
            continue
        parts = set(path.relative_to(REPO_ROOT).parts)
        if parts & SEARCH_SKIP_DIRS or path.is_relative_to(BRAIN):
            continue
        if path.suffix not in CODE_SUFFIXES | {'.md'} and path.name != 'Makefile':
            continue
        for lineno, line in enumerate(read(path).split('\n'), start=1):
            for match in MARKER.finditer(line):
                found[match.group(1)].append('%s:%d' % (rel(path), lineno))
    return found


def article_status(state, folder):
    """Best supported status for one article folder.

    Only 12 of the article folders carry pipeline-state.json; the rest were
    produced by the earlier system and synced in, so their status has to come
    from the artifacts on disk. Nothing is inferred beyond what a file proves.
    """
    if state.get('stage'):
        return str(state['stage'])
    if (folder / 'delivery-manifest.md').exists():
        return 'delivered'
    if (folder / 'qa-report.md').exists():
        return 'qa-passed'
    if (folder / 'draft.md').exists():
        return 'draft-only'
    return 'empty'


def parse_articles():
    """One row per article folder, from state file plus canonical draft."""
    articles = []
    if not BLOG.is_dir():
        return articles
    for folder in sorted(p for p in BLOG.iterdir() if p.is_dir()):
        state = {}
        state_path = folder / 'pipeline-state.json'
        if state_path.exists():
            try:
                state = json.loads(read(state_path))
            except json.JSONDecodeError:
                state = {}

        draft = None
        for name in ('draft-v2-humanized.md', 'draft-v2.md', 'draft.md'):
            if (folder / name).exists():
                draft = folder / name
                break

        meta = {}
        if draft:
            notes, _ = _mpk.split_notes(read(draft))
            meta = _mpk.parse_notes(notes)

        published = ''
        if draft:
            match = re.search(r'[Pp]ublished:?\s*\*?\*?\s*(\d{4}-\d{2}-\d{2})', read(draft)[:4000])
            if match:
                published = match.group(1)

        flags = state.get('flags', {}) if isinstance(state.get('flags'), dict) else {}
        articles.append({
            'slug': folder.name,
            'title': meta.get('title') or state.get('title') or first_heading(read(draft) if draft else ''),
            'status': article_status(state, folder),
            'draft': rel(draft) if draft else '',
            'published': published,
            'focus_keyword': meta.get('focus_keyword', ''),
            'has_state': bool(state),
            'loop_count': state.get('loop_count', ''),
            'panel': state.get('expert_panel', []),
            'qa': (state.get('qa_summary') or {}).get('recommendation', ''),
            'delivered': (folder / 'delivery-manifest.md').exists(),
            'visuals': sorted(p.name for p in folder.glob('*-visual-*.webp')),
            'reviews': len(list((folder / 'expert-reviews').glob('*.md'))) if (folder / 'expert-reviews').is_dir() else 0,
            'seed_topic': flags.get('seed_topic', ''),
            'artifacts': sorted(p.name for p in folder.iterdir() if p.is_file()),
        })
    return articles


ROADMAP_ROW = re.compile(r'^\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|')
STOPWORDS = {'the', 'a', 'an', 'to', 'for', 'of', 'in', 'and', 'or', 'vs', 'with',
             'is', 'are', 'how', 'what', 'when', 'real', 'estate', 'fractional'}


def topic_tokens(text):
    """Comparable tokens from a topic line, a seed string, a slug, or a keyword.

    Light normalisation only, because the point is to compare human phrasings
    of the same subject: parentheticals dropped, thousands separators removed,
    trailing plural stripped. Digit-suffixed tokens keep every reading, so
    "10k" also counts as 10000 and "401k" also counts as 401, which is what
    lets "$10,000" find `how-to-invest-10k` without turning a 401(k) into a
    number nobody wrote.
    """
    text = re.sub(r'\(.*?\)', ' ', text.lower()).replace(',', '')
    tokens = set()
    for raw in re.findall(r"[a-z0-9$%]+", text):
        token = raw.strip('$%')
        if not token:
            continue
        forms = {token}
        thousands = re.fullmatch(r'(\d+)k', token)
        if thousands:
            forms.add(thousands.group(1))
            forms.add(str(int(thousands.group(1)) * 1000))
        if token.endswith('s') and len(token) > 3:
            forms.add(token[:-1])
            forms.discard(token)
        for form in forms:
            if form in STOPWORDS:
                continue
            if len(form) < 3 and not form.isdigit():
                continue
            tokens.add(form)
    return tokens


def best_match(wanted, candidates):
    """(key, recall) of the candidate covering most of `wanted`.

    Ties go to the tightest candidate, so a topic whose only distinctive word
    is "reit" lands on the article about exactly that and not on the longer
    article that merely contains the word.
    """
    if not wanted:
        return '', 0.0
    ranked = []
    for key, tokens in candidates.items():
        if not tokens:
            continue
        ranked.append((len(wanted & tokens) / len(wanted), -len(tokens), key))
    if not ranked:
        return '', 0.0
    ranked.sort(key=lambda item: (-item[0], -item[1], item[2]))
    recall, _, key = ranked[0]
    return key, recall


def parse_topic_pool(articles=None):
    """ROADMAP Step 2 gap table, matched to the article each gap produced.

    Coverage carries its evidence, because the two available signals are not
    equally strong. A state file that records `seed_topic: ROADMAP Step 2 gap
    #N` is the pipeline reporting its own input, but the number is a position
    in a table that has been renumbered since, so the topic text in that seed
    string is what gets matched and a stale number is reported rather than
    trusted. Everything else is token overlap against a folder name, marked
    with its confidence, and never treated as proof that a gap is closed.
    """
    articles = parse_articles() if articles is None else articles
    text = read(ROADMAP)
    in_step2 = False
    topics = []
    for line in text.split('\n'):
        if line.startswith('## Step 2'):
            in_step2 = True
            continue
        if in_step2 and line.startswith('## '):
            break
        if not in_step2:
            continue
        row = ROADMAP_ROW.match(line)
        if row and row.group(1).isdigit():
            topics.append({'num': int(row.group(1)), 'topic': row.group(2).strip(),
                           'why': row.group(3).strip(), 'kd': row.group(4).strip(),
                           'volume': row.group(5).strip(), 'covered_by': '', 'evidence': ''})

    by_num = {t['num']: t for t in topics}
    rows = {t['num']: topic_tokens(t['topic']) for t in topics}

    for article in articles:
        seed = article.get('seed_topic', '')
        if not seed:
            continue
        claimed = re.search(r'gap #(\d+)', seed)
        seed_text = re.sub(r'^.*?gap #\d+\s*[-:]?\s*', '', seed)
        num, ratio = best_match(topic_tokens(seed_text), rows)
        if not num or ratio < 0.5:
            if claimed and int(claimed.group(1)) in by_num:
                topic = by_num[int(claimed.group(1))]
                topic['covered_by'] = topic['covered_by'] or article['slug']
                topic['evidence'] = 'state file, gap number unverified'
            continue
        topic = by_num[num]
        topic['covered_by'] = article['slug']
        if claimed and int(claimed.group(1)) != num:
            topic['evidence'] = 'state file text, its gap #%s is stale' % claimed.group(1)
        else:
            topic['evidence'] = 'state file'

    article_tokens = {a['slug']: topic_tokens(' '.join([a['slug'], a['focus_keyword'], a['title']]))
                      for a in articles}
    for topic in topics:
        if topic['covered_by']:
            continue
        slug, recall = best_match(topic_tokens(topic['topic']), article_tokens)
        if recall >= 0.6:
            topic['covered_by'] = slug
            topic['evidence'] = 'content match ~%d%%' % round(recall * 100)
    return topics


DOC_GROUPS = [
    ('Operating docs', ['README.md', 'ROADMAP.md', 'CONTRIBUTING.md', 'SECURITY.md', 'CLAUDE.md']),
    ('Pipeline and tooling', ['workflow']),
    ('Checklists and gates', ['checklist']),
    ('Brand', ['brand']),
    ('Competitor intelligence', ['competitors']),
]


def parse_sources():
    """Every operational document with its title, purpose, and size."""
    groups = []
    for name, entries in DOC_GROUPS:
        docs = []
        for entry in entries:
            path = REPO_ROOT / entry
            paths = sorted(path.rglob('*.md')) if path.is_dir() else ([path] if path.exists() else [])
            for doc in paths:
                text = read(doc)
                docs.append({'path': rel(doc), 'title': first_heading(text, doc.stem),
                             'purpose': first_prose(text), 'lines': len(text.split('\n'))})
        if docs:
            groups.append((name, docs))
    return groups


