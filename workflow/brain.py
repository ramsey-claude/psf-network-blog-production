#!/usr/bin/env python3
"""
The operation brain: one indexed memory for everything this pipeline knows.

Why this exists: the knowledge that runs this operation is real but scattered.
Active rules live in workflow/incident-log.md, stage contracts in
workflow/pipeline.md, gate criteria across twenty checklists, topic strategy in
ROADMAP.md, brand law in brand/, and per-article truth in 36 blog folders. A
session (human or Claude) that needs to know "what did we decide about X" has
no entry point except reading everything. Knowledge that cannot be recalled on
demand is knowledge the next run re-learns the hard way, which is the exact
failure mode the incident log was created to stop.

The brain has two halves and this script owns both.

  1. Recall. `search` and `rules` retrieve across every markdown file in the
     repo with heading-aware chunking, so a question gets an answer with a
     file:line to verify it against.

  2. Index. `build` regenerates the derived registries under brain/ from their
     upstream sources (never the other way round), and `check` fails when the
     index has drifted from those sources. Anything hand-written under brain/
     is curated knowledge with no upstream; anything generated carries a
     banner and is rebuilt, never edited.

Extraction is deliberately borrowed, not reimplemented: BLOCKING patterns come
from check-rules.py and draft field parsing from make_paste_kit.py, the same
import-the-source pattern qa_battery.py uses, so the brain can never disagree
with the linter or the paste kit about what a rule says or what a draft holds.

Exit codes:
  0  ok
  1  findings (drift, broken reference, failed invariant)
  2  invocation error

Usage:
  python3 workflow/brain.py build                  # regenerate brain/ indexes
  python3 workflow/brain.py check                  # CI gate: index matches sources
  python3 workflow/brain.py search "drive delivery" # ranked recall
  python3 workflow/brain.py rules --category tooling
  python3 workflow/brain.py stats
"""
